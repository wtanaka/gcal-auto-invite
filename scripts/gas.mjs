#!/usr/bin/env node
// Usage: node scripts/gas.mjs <account> <clasp command> [clasp args...]
//
// Each account is a folder accounts/<account>/ holding config.json (who to
// invite, optional overrides) and, after `create`, .clasp.json (script ID).
// Credentials are kept per account by clasp (`--user <account>`).
// Except for login and logout, every command first builds
// accounts/<account>/build/ from src/ plus that config.
import { spawnSync } from "node:child_process";
import {
  cpSync,
  existsSync,
  mkdirSync,
  readFileSync,
  readdirSync,
  rmSync,
  writeFileSync,
} from "node:fs";
import { dirname, join, resolve } from "node:path";
import { fileURLToPath } from "node:url";

const root = resolve(dirname(fileURLToPath(import.meta.url)), "..");
const [account, command, ...rest] = process.argv.slice(2);

// Commands that only deal with credentials: no config or script needed.
const AUTH_ONLY = ["login", "logout"];
// config.json keys that configure the build, not the script.
const BUILD_ONLY_KEYS = ["title", "timeZone", "me"];

function fail(msg) {
  console.error(msg);
  process.exit(1);
}

if (!account || !command || account.startsWith("-")) {
  const names = existsSync(join(root, "accounts"))
    ? readdirSync(join(root, "accounts"), { withFileTypes: true })
        .filter((e) => e.isDirectory())
        .map((e) => e.name)
    : [];
  fail(
    "Usage: npm run gas -- <account> <clasp command>\n" +
      "Commands: login, create, push, status, open-script, tail-logs,\n" +
      "  create-deployment, ... (see `clasp --help`)\n" +
      `Accounts: ${names.join(", ") || "(none)"}`,
  );
}
// Letters, digits and _ - . @ + (so an email address works as a name), never
// starting with a dot and never containing "..".
if (!/^[A-Za-z0-9][A-Za-z0-9._@+-]*$/.test(account) || account.includes("..")) {
  fail(`Bad account name: ${account}`);
}

const clasp = join(root, "node_modules", ".bin", "clasp");
if (!existsSync(clasp)) {
  fail("clasp is not installed. Run `npm install` first.");
}

function runClasp(args, cwd) {
  const r = spawnSync(clasp, args, { cwd, stdio: "inherit" });
  if (r.error) fail(`Could not run clasp: ${r.error.message}`);
  process.exit(r.status ?? 1);
}

if (AUTH_ONLY.includes(command)) {
  runClasp(["--user", account, command, ...rest], root);
}

const accountDir = join(root, "accounts", account);
const configPath = join(accountDir, "config.json");
if (!existsSync(configPath)) {
  fail(
    `Missing ${configPath}\n` +
      `Copy accounts/example/config.json to accounts/${account}/config.json ` +
      "and edit it.",
  );
}
const config = JSON.parse(readFileSync(configPath, "utf8"));

const problems = [];
if (
  !Array.isArray(config.invitees) ||
  config.invitees.length === 0 ||
  config.invitees.some((e) => typeof e !== "string")
) {
  problems.push('"invitees" must be a non-empty array of email strings');
}
for (const key of ["everyHours", "lookaheadDays"]) {
  if (
    config[key] !== undefined &&
    !(Number.isInteger(config[key]) && config[key] > 0)
  ) {
    problems.push(`"${key}" must be a positive integer`);
  }
}
if (
  config.sendUpdates !== undefined &&
  !["none", "all", "externalOnly"].includes(config.sendUpdates)
) {
  problems.push('"sendUpdates" must be "none", "all" or "externalOnly"');
}
if (config.timeZone !== undefined && typeof config.timeZone !== "string") {
  problems.push('"timeZone" must be a string such as "America/Los_Angeles"');
}
if (problems.length > 0) {
  fail(`${configPath}:\n  ${problems.join("\n  ")}`);
}

// Build: src/ plus a generated Config.gs holding this account's settings.
// Defaults live only in src/Code.gs.
const scriptConfig = Object.fromEntries(
  Object.entries(config).filter(([key]) => !BUILD_ONLY_KEYS.includes(key)),
);
const buildDir = join(accountDir, "build");
rmSync(buildDir, { recursive: true, force: true });
mkdirSync(buildDir, { recursive: true });
cpSync(join(root, "src"), buildDir, { recursive: true });
writeFileSync(
  join(buildDir, "Config.gs"),
  `// Generated by scripts/gas.mjs from accounts/${account}/config.json.\n` +
    `var CONFIG = ${JSON.stringify(scriptConfig, null, 2)};\n`,
);
if (config.timeZone) {
  const manifestPath = join(buildDir, "appsscript.json");
  const manifest = JSON.parse(readFileSync(manifestPath, "utf8"));
  manifest.timeZone = config.timeZone;
  writeFileSync(manifestPath, JSON.stringify(manifest, null, 2) + "\n");
}

const claspProject = join(accountDir, ".clasp.json");
if (command !== "create" && !existsSync(claspProject)) {
  fail(`No script yet for "${account}". Run: npm run gas -- ${account} create`);
}
if (command === "create" && existsSync(claspProject)) {
  fail(`${claspProject} already exists; "${account}" already has a script.`);
}

const args = ["--user", account, "--project", accountDir];
if (command === "create") {
  // `create-script` ignores --project and writes .clasp.json into the current
  // directory, so it runs from the account folder. rootDir "build" is relative
  // to that folder.
  args.push(
    "create-script",
    "--type",
    "standalone",
    "--title",
    config.title || "gcal-auto-invite",
    "--rootDir",
    "build",
  );
} else {
  args.push(command);
}
args.push(...rest);

runClasp(args, accountDir);
