#!/usr/bin/env node
// Usage: node scripts/gas.mjs <account> <command> [clasp args...]
//
// Each account is a folder accounts/<account>/ holding config.json (your
// address, who to invite) and, after `create`, .clasp.json (script ID).
// Credentials are kept per account by clasp (`--user <account>`).
// Every command first builds accounts/<account>/build/ from src/ plus that
// config.
import { spawnSync } from "node:child_process";
import {
  cpSync,
  existsSync,
  mkdirSync,
  readFileSync,
  readdirSync,
  rmSync,
  writeFileSync,
} from "node:fs";
import { dirname, join, resolve } from "node:path";
import { fileURLToPath } from "node:url";

const root = resolve(dirname(fileURLToPath(import.meta.url)), "..");
const [account, command, ...rest] = process.argv.slice(2);

function fail(msg) {
  console.error(msg);
  process.exit(1);
}

if (!account || !command || account.startsWith("-")) {
  const names = existsSync(join(root, "accounts"))
    ? readdirSync(join(root, "accounts"), { withFileTypes: true })
        .filter((e) => e.isDirectory())
        .map((e) => e.name)
    : [];
  fail(
    "Usage: npm run gas -- <account> " +
      "<login|create|push|open|logs|status|deploy|...>\n" +
      `Accounts: ${names.join(", ") || "(none)"}`,
  );
}
// Letters, digits and _ - . @ + (so an email address works as a name), never
// starting with a dot and never containing "..".
if (!/^[A-Za-z0-9][A-Za-z0-9._@+-]*$/.test(account) || account.includes("..")) {
  fail(`Bad account name: ${account}`);
}

const accountDir = join(root, "accounts", account);
const configPath = join(accountDir, "config.json");
if (!existsSync(configPath)) {
  fail(
    `Missing ${configPath}\n` +
      `Copy accounts/example/config.json to accounts/${account}/config.json ` +
      "and edit it.",
  );
}
const config = JSON.parse(readFileSync(configPath, "utf8"));
if (
  typeof config.me !== "string" ||
  !Array.isArray(config.invitees) ||
  config.invitees.some((e) => typeof e !== "string")
) {
  fail(`${configPath} needs "me" (string) and "invitees" (array of strings).`);
}
if (
  config.everyHours !== undefined &&
  !(Number.isInteger(config.everyHours) && config.everyHours > 0)
) {
  fail(`${configPath}: "everyHours" must be a positive integer.`);
}

// Build: src/ plus a generated Config.gs holding this account's config.json
// (minus the script title). Defaults live only in src/Code.gs.
const { title: _title, ...scriptConfig } = config;
const buildDir = join(accountDir, "build");
rmSync(buildDir, { recursive: true, force: true });
mkdirSync(buildDir, { recursive: true });
cpSync(join(root, "src"), buildDir, { recursive: true });
writeFileSync(
  join(buildDir, "Config.gs"),
  `// Generated by scripts/gas.mjs from accounts/${account}/config.json.\n` +
    `var CONFIG = ${JSON.stringify(scriptConfig, null, 2)};\n`,
);

const claspProject = join(accountDir, ".clasp.json");
if (command !== "create" && command !== "login" && !existsSync(claspProject)) {
  fail(`No script yet for "${account}". Run: npm run gas -- ${account} create`);
}
if (command === "create" && existsSync(claspProject)) {
  fail(`${claspProject} already exists; "${account}" already has a script.`);
}

const args = ["--user", account, "--project", accountDir];
if (command === "create") {
  // `create-script` ignores --project and writes .clasp.json into the current
  // directory, so it runs from the account folder (see cwd below). rootDir
  // "build" is relative to that folder.
  args.push(
    "create-script",
    "--type",
    "standalone",
    "--title",
    config.title || "gcal-auto-invite",
    "--rootDir",
    "build",
  );
} else {
  args.push(command);
}
args.push(...rest);

const clasp = join(root, "node_modules", ".bin", "clasp");
const r = spawnSync(clasp, args, { cwd: accountDir, stdio: "inherit" });
process.exit(r.status ?? 1);
